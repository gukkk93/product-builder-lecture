function hashCode(str) {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash * 31 + str.charCodeAt(i)) >>> 0;
  }
  return hash;
}

/**
 * Picks compatibility copy for a relation, stable per pair of birthdates.
 * Returns the tier name, the seeded `line` (5 variants, picked same as
 * always), and `goodFit`/`watchFor` — each a fixed { subheading, text }
 * per relation rather than a seeded pick. Unlike `line`, these two are
 * long enough now (multi-paragraph "why this works"/"what to watch for"
 * reads) that a single well-written entry per relation serves better than
 * diluting the same depth across 5 near-duplicate variants.
 */
export function getCompatibilityCopy(lang, relation, seedInput) {
  const entry = (compatibilityTemplates[lang] || compatibilityTemplates.en)[relation];
  const seed = hashCode(seedInput);
  const idx = seed % entry.lines.length;
  return {
    tier: entry.tier,
    line: entry.lines[idx],
    goodFit: entry.goodFit,
    watchFor: entry.watchFor,
  };
}
