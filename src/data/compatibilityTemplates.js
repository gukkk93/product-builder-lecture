function hashCode(str) {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash * 31 + str.charCodeAt(i)) >>> 0;
  }
  return hash;
}

/** Appends the day-pillar flavor clause (see dayGanFlavor) as a second
 * paragraph on a { subheading, text } block, when one is available for this
 * element/field. Leaves the block untouched otherwise, so callers that don't
 * pass a dayGanElement get exactly the old relation-only text back. */
function withDayGanFlavor(block, flavorText) {
  if (!flavorText) return block;
  return { subheading: block.subheading, text: `${block.text}\n\n${flavorText}` };
}

