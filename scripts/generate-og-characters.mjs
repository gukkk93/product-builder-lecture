// Regenerates functions/_lib/characters.js — base64 data URIs for the 5
// element mascots, embedded directly in the og-image.png Cloudflare Pages
// Function (fetching our own static assets from within the Workers runtime
// during image generation is unreliable, so we inline them instead).
// Run this again if src/assets/characters/*.png ever change:
//   node scripts/generate-og-characters.mjs
import fs from 'node:fs';
import path from 'node:path';

const CHAR_DIR = 'src/assets/characters';
const OUT_FILE = 'functions/_lib/characters.js';
const FILE_BY_ELEMENT = { Wood: 'wood.png', Fire: 'fire.png', Earth: 'earth.png', Metal: 'metal.png', Water: 'water.png' };

let out = '// Auto-generated by scripts/generate-og-characters.mjs — do not edit by hand.\n';
out += '// Base64-embedded character mascots for the og-image.png Cloudflare Pages\n';
out += '// Function. See that script for why these are inlined rather than fetched.\n';
out += 'export const CHARACTER_DATA_URI = {\n';
for (const [element, filename] of Object.entries(FILE_BY_ELEMENT)) {
  const buf = fs.readFileSync(path.join(CHAR_DIR, filename));
  out += `  ${element}: 'data:image/png;base64,${buf.toString('base64')}',\n`;
}
out += '};\n';

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, out);
console.log(`wrote ${OUT_FILE} (${fs.statSync(OUT_FILE).size} bytes)`);
